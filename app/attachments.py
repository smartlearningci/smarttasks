"""Anexos do SmartTasks: ficheiros privados no Azure Blob + referência em PostgreSQL.

Demonstração pedagógica: máximo 2 MiB, ficheiros PDF/PNG/JPG/TXT.
"""
import mimetypes
import os
import re
from uuid import uuid4

from azure.core.exceptions import AzureError, ResourceNotFoundError
from azure.storage.blob import BlobServiceClient, ContentSettings
from fastapi import APIRouter, File, HTTPException, UploadFile
from fastapi.responses import Response

from .db import connect

router = APIRouter()
CONTAINER = "smarttasks-anexos"
MAX_BYTES = 2 * 1024 * 1024
EXTENSOES = {".pdf", ".png", ".jpg", ".jpeg", ".txt"}


def initialize_attachments_schema():
    """Acrescenta a tabela de referências sem eliminar dados existentes."""
    with connect() as conn:
        conn.execute("SELECT pg_advisory_xact_lock(250025)")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS task_attachments (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                task_id INTEGER NOT NULL REFERENCES tasks(id),
                blob_name TEXT NOT NULL UNIQUE,
                filename TEXT NOT NULL,
                content_type TEXT NOT NULL,
                size_bytes INTEGER NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )
        """)


def blob_container():
    cs = os.environ.get("AZURE_STORAGE_CONNECTION_STRING")
    if not cs:
        raise HTTPException(503, "Falta AZURE_STORAGE_CONNECTION_STRING.")
    return BlobServiceClient.from_connection_string(cs).get_container_client(CONTAINER)


@router.post("/api/tasks/{task_id}/attachments", status_code=201)
async def upload_attachment(task_id: int, file: UploadFile = File(...)):
    # A demo suporta apenas ficheiros pequenos e extensões conhecidas.
    filename = (file.filename or "anexo.txt").replace(chr(92), "/").split("/")[-1]
    filename = re.sub(r"[^a-zA-Z0-9_.-]", "_", filename)[:100]
    extension = os.path.splitext(filename)[1].lower()
    if extension not in EXTENSOES:
        raise HTTPException(400, "Usar PDF, PNG, JPG ou TXT.")
    content = await file.read(MAX_BYTES + 1)
    if not content or len(content) > MAX_BYTES:
        raise HTTPException(400, "Ficheiro vazio ou superior a 2 MiB.")

    with connect() as conn:
        if not conn.execute("SELECT id FROM tasks WHERE id=%s", (task_id,)).fetchone():
            raise HTTPException(404, "Tarefa não encontrada.")

    blob_name = f"tarefas/{task_id}/{uuid4().hex}{extension}"
    mime = mimetypes.guess_type(filename)[0] or "application/octet-stream"
    try:
        blob = blob_container().get_blob_client(blob_name)
        blob.upload_blob(content, overwrite=False,
                         content_settings=ContentSettings(content_type=mime))
    except AzureError:
        raise HTTPException(502, "O Azure não aceitou o anexo.")

    try:
        with connect() as conn:
            row = conn.execute("""
                INSERT INTO task_attachments
                    (task_id, blob_name, filename, content_type, size_bytes)
                VALUES (%s, %s, %s, %s, %s)
                RETURNING id, task_id, filename, size_bytes
            """, (task_id, blob_name, filename, mime, len(content))).fetchone()
    except Exception:
        # Compensação simples: evita um blob órfão na maioria dos erros SQL.
        try:
            blob.delete_blob()
        except AzureError:
            pass
        raise HTTPException(500, "Não foi possível registar o anexo no PostgreSQL.")
    return row


@router.get("/api/tasks/{task_id}/attachments")
def list_attachments(task_id: int):
    with connect() as conn:
        return conn.execute("""
            SELECT id, task_id, filename, size_bytes, created_at
            FROM task_attachments WHERE task_id=%s ORDER BY id
        """, (task_id,)).fetchall()


@router.get("/api/attachments/{attachment_id}/download")
def download_attachment(attachment_id: int):
    with connect() as conn:
        row = conn.execute("""
            SELECT blob_name, filename, content_type FROM task_attachments
            WHERE id=%s
        """, (attachment_id,)).fetchone()
    if row is None:
        raise HTTPException(404, "Anexo não encontrado.")
    try:
        content = blob_container().get_blob_client(row["blob_name"]).download_blob().readall()
    except ResourceNotFoundError:
        raise HTTPException(404, "O ficheiro já não existe no Azure.")
    except AzureError:
        raise HTTPException(502, "Erro ao obter o ficheiro no Azure.")
    return Response(content, media_type=row["content_type"],
                    headers={"Content-Disposition": f'attachment; filename="{row["filename"]}"'})